const password = "Cuenta ficticia de Playwright";
const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAgAAAAICAIAAABLbSncAAAAE0lEQVR4nGP8v5QBK2DCLjxYJQBM7gG0qfKk0wAAAABJRU5ErkJggg==", "base64");

async function provision(page: Page, base: string, slug: string, name: string) {
  const origin = new URL(base).origin;
  const request = page.request;
  const headers = { Origin: origin };
  const send = async (path: string, data?: object) =>
    request.post(`/api${path}`, { data, headers });
  const email = `admin@${slug}.example.org`;
  expect((await send("/auth/login", { email: "platform@example.org", password })).ok()).toBeTruthy();
  expect((await send("/platform/restaurants", { name, slug, plan_code: "basic" })).ok()).toBeTruthy();
  expect((await send(`/platform/restaurants/${slug}/members`, { email, name: "Administrador", password, role_code: "admin" })).ok()).toBeTruthy();
  expect((await send("/auth/logout")).ok()).toBeTruthy();
  await page.goto("/login");
  await page.getByLabel("Correo electrónico").fill(email);
  await page.getByLabel("Contraseña", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Ingresar" }).click();
  await expect(page.getByRole("heading", { name, exact: true })).toBeVisible();
}

